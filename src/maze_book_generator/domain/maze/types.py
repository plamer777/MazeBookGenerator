"""Общие типы данных конвейера генерации лабиринтов."""

# Точка на прямоугольной сетке: (x, y)
Point = tuple[int, int]

# Маска формы: mask[y][x] == True — ячейка внутри формы лабиринта
Mask = list[list[bool]]

# Стены между ячейками: walls[y][x] = [верх, право, низ, лево], True — стена есть
Walls = list[list[list[bool]]]

# Классическая сетка проходов (обратная совместимость): 0 — стена, 1 — проход
Grid = list[list[int]]

# Ячейка полярного графа: (кольцо, сектор)
Cell = tuple[int, int]

# Граф соединений полярного лабиринта: connections[cell] = множество соседей
Connections = dict[Cell, set[Cell]]
